"""Bronze Lakehouse Storage Engine for ACDP Platform.

Implements Zstandard payload compression, Delta Lake append writes via delta-rs (Rust),
table bin-packing compaction, and DuckDB analytical querying across Tri-Storage backends
(Local POSIX, SeaweedFS, and Cloudflare R2).
"""

import os
from pathlib import Path
from typing import Any

from deltalake import DeltaTable, write_deltalake
import duckdb
import pyarrow as pa
import zstandard as zstd

from acdp.config import AppConfig, settings
from acdp.lakehouse.schema import BRONZE_ARROW_SCHEMA, BronzeRecord

# Reusable Zstandard compressor and decompressor instances
_COMPRESSOR = zstd.ZstdCompressor(level=3)
_DECOMPRESSOR = zstd.ZstdDecompressor()


def compress_payload(content: str | bytes) -> bytes:
    """Compress string or byte content using Zstandard compression (level 3)."""
    if isinstance(content, str):
        payload = content.encode("utf-8")
    else:
        payload = content
    return _COMPRESSOR.compress(payload)


def decompress_payload(compressed: bytes) -> str:
    """Decompress Zstandard compressed bytes back to UTF-8 decoded string."""
    uncompressed_bytes = _DECOMPRESSOR.decompress(compressed)
    return uncompressed_bytes.decode("utf-8")


def records_to_arrow_table(records: list[BronzeRecord]) -> pa.Table:
    """Convert a sequence of BronzeRecord models into an Apache Arrow Table."""
    raw_ids = [r.raw_id for r in records]
    source_urls = [r.source_url for r in records]
    source_domains = [r.source_domain for r in records]
    crawled_ats = [r.crawled_at for r in records]
    http_statuses = [r.http_status for r in records]
    content_types = [r.content_type for r in records]
    content_hashes = [r.content_hash for r in records]
    raw_html_bytes = [r.raw_html_bytes for r in records]
    metadata_jsons = [r.metadata_json for r in records]

    arrays = [
        pa.array(raw_ids, type=pa.string()),
        pa.array(source_urls, type=pa.string()),
        pa.array(source_domains, type=pa.string()),
        pa.array(crawled_ats, type=pa.timestamp("us", tz="UTC")),
        pa.array(http_statuses, type=pa.int32()),
        pa.array(content_types, type=pa.string()),
        pa.array(content_hashes, type=pa.string()),
        pa.array(raw_html_bytes, type=pa.binary()),
        pa.array(metadata_jsons, type=pa.string()),
    ]

    return pa.Table.from_arrays(arrays, schema=BRONZE_ARROW_SCHEMA)


def write_bronze_batch(
    records: list[BronzeRecord],
    config: AppConfig | None = None,
    mode: str = "append",
) -> int:
    """Write a batch of Bronze records to the Delta Lake table.

    Args:
        records: List of BronzeRecord instances to write.
        config: Application configuration instance (defaults to global settings).
        mode: Delta write mode ('append' or 'overwrite').

    Returns:
        Number of records successfully written.
    """
    if not records:
        return 0

    cfg = config or settings
    table_uri = cfg.bronze_storage_uri
    storage_options = cfg.get_storage_options()

    # Ensure parent directory exists for local paths
    if cfg.bronze_storage_backend == "local" and not table_uri.startswith(("s3://", "r2://")):
        Path(table_uri).mkdir(parents=True, exist_ok=True)

    arrow_table = records_to_arrow_table(records)

    write_deltalake(
        table_or_uri=table_uri,
        data=arrow_table,
        mode=mode,
        storage_options=storage_options or None,
    )


    return len(records)


def optimize_bronze_table(config: AppConfig | None = None) -> None:
    """Execute bin-packing compaction on the Bronze Delta Lake table.

    Consolidates fragmented Parquet files generated by micro-batches.
    """
    cfg = config or settings
    table_uri = cfg.bronze_storage_uri
    storage_options = cfg.get_storage_options()

    dt = DeltaTable(table_uri, storage_options=storage_options or None)
    dt.optimize.compact()


def get_delta_table(config: AppConfig | None = None) -> DeltaTable:
    """Obtain a DeltaTable handle for inspecting metadata, versions, and files."""
    cfg = config or settings
    table_uri = cfg.bronze_storage_uri
    storage_options = cfg.get_storage_options()
    return DeltaTable(table_uri, storage_options=storage_options or None)


def query_bronze_with_duckdb(
    sql_query: str,
    config: AppConfig | None = None,
    con: duckdb.DuckDBPyConnection | None = None,
) -> duckdb.DuckDBPyRelation:
    """Execute an analytical SQL query against the Bronze Delta table via DuckDB.

    Automatically configures DuckDB S3/httpfs settings for SeaweedFS or Cloudflare R2.
    """
    cfg = config or settings
    connection = con or duckdb.connect()

    # Load delta extension
    try:
        connection.execute("LOAD delta;")
    except Exception:
        connection.execute("INSTALL delta; LOAD delta;")

    # Configure S3 options if accessing cloud or Docker S3 endpoint
    table_uri = cfg.bronze_storage_uri
    if table_uri.startswith(("s3://", "r2://")):
        try:
            connection.execute("LOAD httpfs;")
        except Exception:
            connection.execute("INSTALL httpfs; LOAD httpfs;")

        if cfg.aws_endpoint_url:
            # Strip http:// or https:// for s3_endpoint if necessary, or use as is
            endpoint = cfg.aws_endpoint_url.replace("http://", "").replace("https://", "")
            connection.execute(f"SET s3_endpoint = '{endpoint}';")
        if cfg.aws_access_key_id:
            connection.execute(f"SET s3_access_key_id = '{cfg.aws_access_key_id}';")
        if cfg.aws_secret_access_key:
            connection.execute(f"SET s3_secret_access_key = '{cfg.aws_secret_access_key}';")
        if cfg.aws_region:
            connection.execute(f"SET s3_region = '{cfg.aws_region}';")

        use_ssl = "false" if cfg.aws_allow_http else "true"
        connection.execute(f"SET s3_use_ssl = {use_ssl};")
        connection.execute("SET s3_url_style = 'path';")

    return connection.query(sql_query)
